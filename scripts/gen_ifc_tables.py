"""Generate interoperability facts, never schema source or descriptive text."""
from pathlib import Path
from pprint import pformat
import ifcopenshell
from ifcopenshell import ifcopenshell_wrapper as wrapper


def generate():
    schemas = {}
    for version in ('IFC4', 'IFC4X3_ADD2'):
        schema = wrapper.schema_by_name(version)
        entities = {d.name(): d for d in schema.declarations() if isinstance(d, wrapper.entity)}
        classes, orders, enums = {}, {}, {}
        for name, entity in sorted(entities.items()):
            orders[name.upper()] = [a.name() for a in entity.all_attributes()]
            chain = []
            parent = entity
            while parent:
                chain.append(parent.name())
                parent = parent.supertype()
            enum_attrs = {}
            for attr in entity.all_attributes():
                typ = attr.type_of_attribute()
                if hasattr(typ, 'declared_type'):
                    typ = typ.declared_type()
                if isinstance(typ, wrapper.enumeration_type):
                    enum_attrs[attr.name()] = {'name': typ.name(), 'members': list(typ.enumeration_items()), 'required': not attr.optional()}
            enums[name.upper()] = enum_attrs
            if not any(base in chain for base in ('IfcElement', 'IfcSpatialElement', 'IfcGroup')):
                continue
            if entity.is_abstract() and name != 'IfcFacilityPart':
                continue
            domain = 'other'
            for base, bucket in [('IfcBuiltElement', 'building'), ('IfcBuildingElement', 'building'),
                                 ('IfcCivilElement', 'infrastructure/transport'), ('IfcTransportationDevice', 'infrastructure/transport'),
                                 ('IfcDistributionElement', 'MEP/distribution'), ('IfcReinforcingElement', 'structural'),
                                 ('IfcSpatialElement', 'spatial'), ('IfcGroup', 'group')]:
                if base in chain:
                    domain = bucket
            counterpart = next((entities[base + 'Type'] for base in chain
                                if base + 'Type' in entities and not entities[base + 'Type'].is_abstract()), None)
            pt = enum_attrs.get('PredefinedType', {})
            classes[name] = dict(domain=domain, type_class=counterpart.name() if counterpart and not counterpart.is_abstract() else None,
                                 enum_name=pt.get('name'), predefined_types=pt.get('members', []))
        schemas[version] = dict(classes=classes, orders=orders, enums=enums)
    target = Path(__file__).resolve().parents[1] / 'core/ifc_tables_data.py'
    target.write_text('# SPDX-License-Identifier: GPL-3.0-or-later\n'
                      + f'"""Generated by scripts/gen_ifc_tables.py using IfcOpenShell {ifcopenshell.version}; IFC4 and IFC4X3_ADD2. Facts only."""\n'
                      + 'SCHEMA_DATA = ' + pformat(schemas, width=120, sort_dicts=True) + '\n')


if __name__ == '__main__':
    generate()
